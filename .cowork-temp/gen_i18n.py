def unescape(s):
    out = []
    i = 0
    while i < len(s):
        c = s[i]
        if c == '\\':
            n = s[i+1]
            if n == 'n': out.append('\n'); i += 2
            elif n == 't': out.append('\t'); i += 2
            elif n == '"': out.append('"'); i += 2
            elif n == '\\': out.append('\\'); i += 2
            elif n == '/': out.append('/'); i += 2
            elif n == 'r': out.append('\r'); i += 2
            elif n == 'u': out.append(chr(int(s[i+2:i+6], 16))); i += 6
            else: out.append(n); i += 2
        else:
            out.append(c); i += 1
    return ''.join(out)


def parse_entry(line):
    # returns (keyraw, valraw) where both include surrounding quotes
    assert line[0] == '"'
    i = 1
    while True:
        if line[i] == '\\':
            i += 2; continue
        if line[i] == '"':
            break
        i += 1
    keyraw = line[0:i+1]
    assert line[i+1:i+3] == ': ', repr(line)
    valraw = line[i+3:].strip()
    return keyraw, valraw


def build(table, lang_comment, outpath):
    data = io.open(SRC, encoding='utf-8').read()
    eol = '\r\n' if '\r\n' in data else '\n'
    lines = data.replace('\r\n', '\n').split('\n')
    out_lines = []
    missing = []
    for idx, ln in enumerate(lines):
        st = ln.lstrip()
        if st.startswith('#') or st == '':
            if idx == 0:
                out_lines.append(lang_comment)
            else:
                out_lines.append(ln)
            continue
        keyraw, valraw = parse_entry(ln)
        assert valraw.startswith('"') and valraw.endswith('"'), repr(ln)
        key = unescape(keyraw[1:-1])
        if key not in table:
            missing.append(key)
            out_lines.append(ln)
            continue
        val = table[key]
        kenc = json.dumps(key, ensure_ascii=False)
        venc = json.dumps(val, ensure_ascii=False)
        out_lines.append('%s: %s' % (kenc, venc))
    if missing:
        print('MISSING for', outpath)
        for m in missing:
            print(repr(m))
        raise SystemExit(1)
    text = eol.join(out_lines)
    io.open(outpath, 'w', encoding='utf-8', newline='').write(text)
    print('wrote', outpath, 'entries_lines', len(lines))


