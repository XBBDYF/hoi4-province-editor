LINE_RE = re.compile(r'^("(?:[^"\\]|\\.)*")\s*:\s*"(.*)"\s*$')


def esc(s):
    out = []
    for ch in s:
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\t':
            out.append('\\t')
        else:
            out.append(ch)
    return ''.join(out)


def build(src_lines, table, header):
    res = [header, '']
    keys_seen = []
    missing = []
    for line in src_lines:
        st = line.strip()
        if st == '':
            if res and res[-1] != '':
                res.append('')
            continue
        if st.startswith('#'):
            continue
        m = LINE_RE.match(line)
        if not m:
            raise SystemExit('UNPARSED: ' + repr(line))
        key_raw, _val = m.group(1), m.group(2)
        key = yaml.safe_load(key_raw)
        if key not in table:
            missing.append(key)
            continue
        keys_seen.append(key)
        res.append('%s: "%s"' % (key_raw, esc(table[key])))
    while res and res[-1] == '':
        res.pop()
    return '\n'.join(res) + '\n', keys_seen, missing


